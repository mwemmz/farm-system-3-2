-- Developer 1 Phase 3: field-based harvest records; canonical quantities are kilograms.
CREATE TABLE IF NOT EXISTS harvests (
    id INT AUTO_INCREMENT PRIMARY KEY,
    field_id INT NOT NULL,
    crop_name_snapshot VARCHAR(255) NOT NULL,
    variety_snapshot VARCHAR(255) NULL,
    expected_harvest_date DATE NULL,
    actual_harvest_date DATE NULL,
    expected_quantity_kg DECIMAL(15,4) NULL,
    actual_quantity_kg DECIMAL(15,4) NULL,
    loss_quantity_kg DECIMAL(15,4) NOT NULL DEFAULT 0,
    area_harvested_hectares DECIMAL(15,4) NULL,
    grade VARCHAR(100) NULL,
    quality_notes TEXT NULL,
    status ENUM('planned','in_progress','completed','cancelled') NOT NULL DEFAULT 'planned',
    notes TEXT NULL,
    created_by_user_id INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_harvest_field_status (field_id, status),
    INDEX idx_harvest_expected_date (expected_harvest_date),
    INDEX idx_harvest_actual_date (actual_harvest_date),
    INDEX idx_harvest_creator (created_by_user_id),
    CONSTRAINT fk_harvest_field FOREIGN KEY (field_id) REFERENCES fields(id) ON DELETE RESTRICT,
    CONSTRAINT fk_harvest_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_harvest_expected CHECK (expected_quantity_kg IS NULL OR expected_quantity_kg > 0),
    CONSTRAINT chk_harvest_actual CHECK (actual_quantity_kg IS NULL OR actual_quantity_kg >= 0),
    CONSTRAINT chk_harvest_loss CHECK (loss_quantity_kg >= 0 AND (actual_quantity_kg IS NOT NULL OR loss_quantity_kg = 0) AND (actual_quantity_kg IS NULL OR loss_quantity_kg <= actual_quantity_kg)),
    CONSTRAINT chk_harvest_area CHECK (area_harvested_hectares IS NULL OR area_harvested_hectares > 0),
    CONSTRAINT chk_harvest_completed CHECK (status <> 'completed' OR (actual_harvest_date IS NOT NULL AND actual_quantity_kg IS NOT NULL AND area_harvested_hectares IS NOT NULL))
);
