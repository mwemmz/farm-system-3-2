-- Developer 1 Phase 2B: field pest and disease scouting.
CREATE TABLE IF NOT EXISTS pest_disease_catalog (
    id INT AUTO_INCREMENT PRIMARY KEY,
    issue_type ENUM('pest','disease') NOT NULL,
    common_name VARCHAR(255) NOT NULL,
    scientific_name VARCHAR(255) NULL,
    description TEXT NULL,
    common_symptoms TEXT NULL,
    recommended_control TEXT NULL,
    prevention_notes TEXT NULL,
    default_severity ENUM('low','moderate','high','critical') NULL,
    status ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_catalog_type_name (issue_type, common_name),
    INDEX idx_catalog_status_type (status, issue_type)
);

CREATE TABLE IF NOT EXISTS scouting_reports (
    id INT AUTO_INCREMENT PRIMARY KEY,
    field_id INT NOT NULL,
    catalog_id INT NULL,
    observed_issue_name VARCHAR(255) NULL,
    observed_at DATETIME NOT NULL,
    severity ENUM('low','moderate','high','critical') NOT NULL,
    affected_area_hectares DECIMAL(15,4) NULL,
    incidence_percent DECIMAL(5,2) NULL,
    symptoms_notes TEXT NULL,
    recommended_action_notes TEXT NULL,
    status ENUM('open','monitoring','treated','resolved') NOT NULL DEFAULT 'open',
    reported_by_user_id INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_scout_field_observed (field_id, observed_at),
    INDEX idx_scout_catalog_observed (catalog_id, observed_at),
    INDEX idx_scout_reporter (reported_by_user_id),
    CONSTRAINT fk_scout_field FOREIGN KEY (field_id) REFERENCES fields(id) ON DELETE RESTRICT,
    CONSTRAINT fk_scout_catalog FOREIGN KEY (catalog_id) REFERENCES pest_disease_catalog(id) ON DELETE RESTRICT,
    CONSTRAINT fk_scout_reporter FOREIGN KEY (reported_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_scout_issue CHECK (catalog_id IS NOT NULL OR (observed_issue_name IS NOT NULL AND CHAR_LENGTH(TRIM(observed_issue_name)) > 0)),
    CONSTRAINT chk_scout_area CHECK (affected_area_hectares IS NULL OR affected_area_hectares > 0),
    CONSTRAINT chk_scout_incidence CHECK (incidence_percent IS NULL OR incidence_percent BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS treatments (
    id INT AUTO_INCREMENT PRIMARY KEY,
    scouting_report_id INT NOT NULL,
    treatment_type ENUM('chemical','biological','mechanical','cultural','other') NOT NULL,
    product_or_method VARCHAR(255) NOT NULL,
    active_ingredient VARCHAR(255) NULL,
    application_rate DECIMAL(15,4) NULL,
    application_rate_unit VARCHAR(100) NULL,
    quantity_used DECIMAL(15,4) NULL,
    quantity_unit VARCHAR(100) NULL,
    applied_at DATETIME NULL,
    status ENUM('planned','applied','monitoring','completed') NOT NULL DEFAULT 'planned',
    effectiveness_percent DECIMAL(5,2) NULL,
    effectiveness_notes TEXT NULL,
    follow_up_date DATE NULL,
    created_by_user_id INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_treatment_report_created (scouting_report_id, created_at),
    INDEX idx_treatment_creator (created_by_user_id),
    CONSTRAINT fk_treatment_report FOREIGN KEY (scouting_report_id) REFERENCES scouting_reports(id) ON DELETE RESTRICT,
    CONSTRAINT fk_treatment_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_treatment_rate CHECK (application_rate IS NULL OR application_rate > 0),
    CONSTRAINT chk_treatment_quantity CHECK (quantity_used IS NULL OR quantity_used > 0),
    CONSTRAINT chk_treatment_effectiveness CHECK (effectiveness_percent IS NULL OR effectiveness_percent BETWEEN 0 AND 100)
);
