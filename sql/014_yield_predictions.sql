-- Developer 1 Phase 4: historical/statistical field yield estimates.
CREATE TABLE IF NOT EXISTS yield_predictions (
    id INT AUTO_INCREMENT PRIMARY KEY,
    field_id INT NOT NULL,
    crop_name_snapshot VARCHAR(255) NOT NULL,
    variety_snapshot VARCHAR(255) NULL,
    target_area_hectares DECIMAL(15,4) NOT NULL,
    predicted_yield_kg_per_hectare DECIMAL(15,4) NOT NULL,
    predicted_quantity_kg DECIMAL(15,4) NOT NULL,
    historical_mean_yield_kg_per_hectare DECIMAL(15,4) NOT NULL,
    historical_min_yield_kg_per_hectare DECIMAL(15,4) NOT NULL,
    historical_max_yield_kg_per_hectare DECIMAL(15,4) NOT NULL,
    historical_stddev DECIMAL(15,4) NOT NULL,
    coefficient_of_variation DECIMAL(15,4) NULL,
    sample_count INT NOT NULL,
    confidence_level ENUM('low','medium','high') NOT NULL,
    prediction_method VARCHAR(50) NOT NULL,
    factor_context_json LONGTEXT NULL,
    created_by_user_id INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_prediction_field_created (field_id, created_at),
    INDEX idx_prediction_crop (crop_name_snapshot),
    INDEX idx_prediction_created (created_at),
    INDEX idx_prediction_creator (created_by_user_id),
    CONSTRAINT fk_prediction_field FOREIGN KEY (field_id) REFERENCES fields(id) ON DELETE RESTRICT,
    CONSTRAINT fk_prediction_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_prediction_area CHECK (target_area_hectares > 0),
    CONSTRAINT chk_prediction_yield CHECK (predicted_yield_kg_per_hectare >= 0 AND predicted_quantity_kg >= 0),
    CONSTRAINT chk_prediction_history CHECK (historical_mean_yield_kg_per_hectare >= 0 AND historical_min_yield_kg_per_hectare >= 0 AND historical_max_yield_kg_per_hectare >= historical_min_yield_kg_per_hectare AND historical_stddev >= 0),
    CONSTRAINT chk_prediction_cv CHECK (coefficient_of_variation IS NULL OR coefficient_of_variation >= 0),
    CONSTRAINT chk_prediction_samples CHECK (sample_count >= 2)
);
